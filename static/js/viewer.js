// Translation viewer (Phase 4): a single page's image with semi-transparent bbox
// overlays; tap/click a box to reveal its translation. Prev/next navigation is hash
// navigation (full remount per page), and live updates stream in as translations complete.
import { api } from './api.js';
import { el, toast } from './state.js';

export function renderViewer(container, params) {
  const workId = Number(params.id);
  const imageId = Number(params.imageId);
  if (!Number.isInteger(workId) || workId <= 0 || !Number.isInteger(imageId) || imageId <= 0) {
    container.replaceChildren(el('p', { text: 'Invalid viewer route.' }));
    return;
  }

  let disposed = false;

  // --- navigation state -----------------------------------------------------
  let images = [];        // ordered list (sort_order ASC) for prev/next bounds + title
  let currentIndex = -1;

  // --- result / overlay state -----------------------------------------------
  let regions = null;     // array of region objects; null until first fetch resolves
  let hasResult = false;   // true once we know a result exists (vs. not-yet-translated)
  let contextAfter = null; // LLM-generated page context (from result row), null until loaded
  let showOriginal = false; // tooltip mode: original text vs translated text
  let cycleKey = null;     // signature of the overlap cluster currently being cycled
  let cycleIdx = 0;        // position within that cluster

  // --- live update state ----------------------------------------------------
  let liveProgress = null; // latest job progress % while translating, else null
  let ws = null;

  // --- chrome ---------------------------------------------------------------
  const backLink = el('a', { class: 'back', href: `#/${workId}`, text: '← Back to work' });
  const titleEl = el('h1', { text: 'Loading…' });
  const img = el('img', { alt: '', draggable: 'false' });
  const stage = el('div', { class: 'viewer-stage' }, [img]);
  const prevBtn = el('button', { class: 'btn nav-btn', text: '← Prev' });
  const nextBtn = el('button', { class: 'btn nav-btn', text: 'Next →' });
  const counter = el('span', { class: 'viewer-counter muted', text: '' });
  const infoLine = el('p', { class: 'viewer-info muted', text: '' });

  // Bottom controls + context sections (below the fold on mobile).
  const origToggle = el('input', { type: 'checkbox' });
  const controlsRow = el('div', { class: 'viewer-controls' }, [
    el('label', { class: 'toggle-label' }, [origToggle, ' Show original (untranslated) text']),
  ]);
  const ctxBody = el('p', { class: 'ctx-text' });
  const ctxSection = el('details', { class: 'viewer-section', open: '' }, [
    el('summary', { text: 'Page context — generated by the LLM' }),
    ctxBody,
  ]);
  const descArea = el('textarea', {
    class: 'ctx-edit', rows: '3', placeholder: 'Optional extra context for the translator…',
  });
  const saveBtn = el('button', { class: 'btn touch-btn', text: 'Save description' });
  const descSection = el('div', { class: 'viewer-section' }, [
    el('h2', { class: 'section-title', text: 'Image description — extra context for the LLM' }),
    descArea,
    saveBtn,
  ]);

  container.replaceChildren(
    el('div', { class: 'view-header' }, [backLink, titleEl]),
    el('div', { class: 'viewer-stage-wrap' }, [stage]),
    el('div', { class: 'viewer-nav' }, [prevBtn, counter, nextBtn]),
    infoLine,
    controlsRow,
    ctxSection,
    descSection,
  );

  // --- overlay boxes --------------------------------------------------------
  // Each region is a div anchored at its bbox, carrying a hidden tooltip just outside it.
  // Reveal = hover (desktop peek) or click/tap; clicking where boxes overlap cycles through
  // the stacked boxes so you can reach the one underneath.
  function tipText(region) {
    const orig = region.original_text || '', trans = region.translated_text || '';
    return showOriginal ? (orig || trans) : (trans || orig);
  }

  function applyTipTexts() {
    if (!regions) return;
    const tips = stage.querySelectorAll('.bbox-tip');
    regions.forEach((region, i) => { if (tips[i]) tips[i].textContent = tipText(region); });
  }

  /**
   * Compute tooltip layout for a region.
   * - `above`: boxes in the lower half show their tip above to stay on-screen.
   * - `right` / `maxW`: extend toward whichever side has more horizontal room so
   *   long text wraps down inside the screen instead of spilling off it.
   */
  function tipLayout(region, stageWidth) {
    const [x1 = 0, y1 = 0, x2 = 0, y2 = 0] = region.bbox || [];
    const above = (y1 + y2) / 2 > 0.5;
    const roomLeft = x2 * stageWidth;
    const roomRight = (1 - x1) * stageWidth;
    const right = roomLeft >= roomRight;
    const maxW = Math.max(120, Math.min(320, (right ? roomLeft : roomRight) - 8));
    return { above, right, maxW };
  }

  function renderBoxes() {
    for (const b of [...stage.querySelectorAll('.bbox')]) b.remove();
    if (!regions) return;
    const W = stage.clientWidth || window.innerWidth; // rendered image width, for tip fit
    regions.forEach((region, i) => {
      const [x1 = 0, y1 = 0, x2 = 0, y2 = 0] = region.bbox || [];
      const { above, right, maxW } = tipLayout(region, W);

      const box = el('div', {
        class: 'bbox' + (above ? ' above' : '') + (right ? ' tip-right' : ''),
        style: `left:${(x1 * 100).toFixed(3)}%;top:${(y1 * 100).toFixed(3)}%;` +
              `width:${((x2 - x1) * 100).toFixed(3)}%;height:${((y2 - y1) * 100).toFixed(3)}%`,
        tabindex: '0',
        'aria-label': `Region ${i + 1}`,
      });
      const tip = el('div', { class: 'bbox-tip', text: tipText(region) });
      tip.style.maxWidth = `${maxW}px`; // cap to the room on the chosen side -> wraps down
      box.appendChild(tip);
      stage.appendChild(box);
    });
  }

  function setOpen(i) {
    for (const b of [...stage.querySelectorAll('.bbox.open')]) b.classList.remove('open');
    const boxes = stage.querySelectorAll('.bbox');
    if (boxes[i]) boxes[i].classList.add('open');
    stage.classList.add('has-open');
  }

  function clearOpen() {
    for (const b of [...stage.querySelectorAll('.bbox.open')]) b.classList.remove('open');
    stage.classList.remove('has-open');
    cycleKey = null;
    cycleIdx = 0;
  }

  /**
   * Delegated click handler on the stage.
   *
   * Hit-tests the click point geometrically so overlapping boxes are all
   * reachable: clicking where N boxes overlap cycles through them one at a
   * time (frontmost first). A single box toggles off on the second click.
   */
  function onClickStage(e) {
    if (!regions) return;

    // 1. Convert to normalized stage coordinates and collect all hit regions.
    const rect = stage.getBoundingClientRect();
    const px = (e.clientX - rect.left) / rect.width;
    const py = (e.clientY - rect.top) / rect.height;
    const cands = [];
    regions.forEach((region, i) => {
      const [x1 = 0, y1 = 0, x2 = 0, y2 = 0] = region.bbox || [];
      if (px >= x1 && px <= x2 && py >= y1 && py <= y2) cands.push(i);
    });

    // 2. Frontmost (last drawn) first so cycling starts on the visible box.
    cands.reverse();

    // 3. Clicked empty space → dismiss any open tooltip.
    if (!cands.length) { clearOpen(); return; }

    // 4. Track which overlap cluster we're cycling through. The key is the
    //    sorted set of indices — same cluster advances, new cluster resets.
    const key = [...cands].sort((a, b) => a - b).join(',');
    if (key === cycleKey) cycleIdx = (cycleIdx + 1) % cands.length;
    else { cycleKey = key; cycleIdx = 0; }

    // 5. A lone box toggles off on the second click.
    const target = cands[cycleIdx];
    if (cands.length === 1 && stage.querySelectorAll('.bbox')[target].classList.contains('open')) {
      clearOpen();
      return;
    }
    setOpen(target);
  }

  function renderInfo() {
    let msg;
    if (liveProgress != null) msg = `Translating… ${liveProgress}%`;
    else if (!hasResult) msg = 'No translation for this page yet.';
    else if (!regions || !regions.length) msg = 'No text regions detected on this page.';
    else msg = 'Hover or tap a box to see its translation — click again where boxes overlap to cycle through them.';
    infoLine.textContent = msg;
  }

  async function loadResult() {
    const id = images[currentIndex].id;
    try {
      const row = await api.getImageResult(id);
      if (disposed) return;
      regions = Array.isArray(row.result_data) ? row.result_data : [];
      hasResult = true;
      contextAfter = typeof row.context_after === 'string' ? row.context_after : null;
    } catch (e) {
      if (disposed) return;
      // 404 == "no result yet"; anything else is a real error but we still show the image.
      regions = [];
      hasResult = /^404/.test(String(e.message));
      contextAfter = null;
      if (!hasResult) toast(e.message, 'error');
    }
    cycleKey = null;
    cycleIdx = 0;
    stage.classList.remove('has-open');
    renderBoxes();
    renderCtx();
    renderInfo();
  }

  function renderCtx() {
    ctxBody.textContent = contextAfter
      || (hasResult ? '(none generated for this page)'
                   : 'No translation yet — the LLM context appears once this page is translated.');
  }

  function updateNav() {
    prevBtn.disabled = currentIndex <= 0;
    nextBtn.disabled = currentIndex >= images.length - 1;
    counter.textContent = images.length ? `Page ${currentIndex + 1} of ${images.length}` : '';
  }

  // --- data loading ---------------------------------------------------------
  async function loadImages() {
    try { images = await api.listImages(workId); } catch (e) { toast(e.message, 'error'); return; }
    if (disposed) return;
    currentIndex = images.findIndex((i) => i.id === imageId);
    if (currentIndex < 0) {
      container.replaceChildren(el('p', { text: 'Image not found in this work.' }), backLink);
      return;
    }
    const m = images[currentIndex];
    descArea.value = m.context || '';
    titleEl.textContent = m.original_name;
    document.title = `${m.original_name} — llmanga-translator`;
    img.src = api.imageUrl(m.id);
    img.alt = m.original_name;
    updateNav();
    loadResult();
  }

  // --- navigation -----------------------------------------------------------
  prevBtn.addEventListener('click', () => {
    if (currentIndex > 0) location.hash = `#/${workId}/image/${images[currentIndex - 1].id}`;
  });
  nextBtn.addEventListener('click', () => {
    if (currentIndex < images.length - 1) location.hash = `#/${workId}/image/${images[currentIndex + 1].id}`;
  });

  function onKey(e) {
    if (e.key === 'ArrowLeft' && currentIndex > 0) prevBtn.click();
    else if (e.key === 'ArrowRight' && currentIndex < images.length - 1) nextBtn.click();
  }
  window.addEventListener('keydown', onKey);

  // --- live updates ---------------------------------------------------------
  let reconnectTimer = null; // auto-reconnect backoff timer
  let reconnectAttempts = 0;

  function connectWs() {
    if (ws || disposed) return;
    const url = api.wsUrl(workId);
    try {
      console.log('[viewer-ws] connecting', { url, workId });
      ws = new WebSocket(url);
    } catch (e) {
      console.error('[viewer-ws] could not open live connection', { url, workId, error: e && e.message });
      scheduleReconnect();
      return;
    }
    const log = (...args) => console.log('[viewer-ws]', ...args);
    ws.onopen = () => { reconnectAttempts = 0; log('OPEN', { url, readyState: ws.readyState }); };
    ws.onmessage = (ev) => {
      let m;
      try { m = JSON.parse(ev.data); }
      catch (e) { console.warn('[viewer-ws] unparseable message', ev.data, e); return; }
      log('MSG', m.type, m.data || {});
      handleEvent(m);
    };
    ws.onerror = (ev) => console.error('[viewer-ws] ERROR event', { url, readyState: ws.readyState, error: ev && ev.message });
    ws.onclose = (ev) => {
      log('CLOSE', { code: ev.code, reason: ev.reason || '', wasClean: ev.wasClean });
      ws = null;
      if (!disposed) scheduleReconnect(); // auto-reconnect so live updates resume after a drop
    };
  }

  // Auto-reconnect with exponential backoff (1s, 2s, 4s … capped at 15s).
  function scheduleReconnect() {
    if (disposed || reconnectTimer) return;
    const delay = Math.min(15000, 1000 * 2 ** reconnectAttempts);
    reconnectAttempts += 1;
    console.log('[viewer-ws] scheduling reconnect in', delay, 'ms');
    reconnectTimer = setTimeout(() => { reconnectTimer = null; connectWs(); }, delay);
  }

  // Re-attach to an in-flight job after a page reload so the progress line shows up
  // immediately instead of waiting for the next WebSocket event.
  async function restoreLiveState() {
    try {
      const job = await api.getActiveJob(workId);
      if (disposed || !job) return;
      liveProgress = typeof job.progress === 'number' ? Math.round(job.progress) : null;
      renderInfo();
    } catch { /* non-fatal: the WebSocket will update it anyway */ }
  }

  function handleEvent(msg) {
    if (!msg || !msg.type) return;
    const d = msg.data || {};
    const currentId = images[currentIndex] && images[currentIndex].id;
    switch (msg.type) {
      case 'translation_complete':
        if (d.image_id !== currentId) break;
        liveProgress = null;
        loadResult(); // this page just finished — redraw its boxes live
        break;
      case 'job_status':
        liveProgress = typeof d.progress === 'number' ? Math.round(d.progress) : null;
        renderInfo();
        break;
      case 'job_complete':
        liveProgress = null;
        loadResult(); // refresh in case the current page was the last one done
        break;
    }
  }

  origToggle.addEventListener('change', () => {
    showOriginal = origToggle.checked;
    applyTipTexts();
  });

  saveBtn.addEventListener('click', async () => {
    const id = images[currentIndex].id;
    const value = descArea.value.trim();
    if (value === ((images[currentIndex] && images[currentIndex].context) || '').trim()) return; // unchanged
    saveBtn.disabled = true;
    try {
      await api.updateImage(id, { context: value });
      images[currentIndex].context = value;
      toast('Description saved.', 'success');
    } catch (e) {
      toast(e.message, 'error');
    } finally {
      saveBtn.disabled = false;
    }
  });

  stage.addEventListener('click', onClickStage);

  // Refit tips when the stage width changes (mobile rotate/resize): recompute each tip's
  // max-width so long text wraps down inside the new width instead of spilling off-screen.
  let resizeTimer = null;
  function refitTips() {
    const openIdx = [...stage.querySelectorAll('.bbox')].findIndex((b) => b.classList.contains('open'));
    renderBoxes();
    if (openIdx >= 0) setOpen(openIdx);
  }
  function onResize() { clearTimeout(resizeTimer); resizeTimer = setTimeout(refitTips, 120); }
  window.addEventListener('resize', onResize);

  connectWs();
  restoreLiveState();
  loadImages();

  return () => {
    disposed = true;
    if (reconnectTimer) clearTimeout(reconnectTimer);
    if (ws) { try { ws.close(); } catch {} ws = null; }
    window.removeEventListener('keydown', onKey);
    window.removeEventListener('resize', onResize);
    clearTimeout(resizeTimer);
    stage.removeEventListener('click', onClickStage);
    document.title = 'llmanga-translator';
  };
}
